#!/usr/bin/env python3
"""Build site/data.js from the benchmark, so the landing page never shows a
number the benchmark did not produce.

Everything the page counts comes from here:
  - the normal and singkat replies, split into real o200k_base tokens
  - which tokens are fluff (the spans below), and their category
  - the three mode replies with their token counts
  - abbreviation vs full word, with the actual token pieces
  - benchmark totals per mode

Run from the repo root:
    .venv/bin/python site/tools/build-data.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import tiktoken

ROOT = Path(__file__).resolve().parents[2]
SAMPLES = json.loads((ROOT / "benchmarks" / "samples.json").read_text(encoding="utf-8"))
OUT = ROOT / "site" / "data.js"
ENC = tiktoken.get_encoding("o200k_base")
SAMPLE_ID = "react-rerender"
MODES = ["singkat", "jaksel", "sunda"]

# Fluff spans in the normal reply, listed in TEXT order (repeated words are
# matched left to right). Each span must start and end on a token boundary; the
# script fails otherwise, so a sample edit cannot silently mislabel half a token.
# (category, exact text including its leading space)
FLUFF = [
    ("pembuka", "Tentu, saya akan membantu menjelaskan masalah ini!"),
    ("sapaan", " Anda"),
    ("ragu-ragu", " kemungkinan besar"),
    ("kata kosong", " melakukan"),
    ("kata kosong", " sebuah"),
    ("kata kosong", " secara"),
    ("kata kosong", " bahwa"),
    ("kata kosong", " melakukan"),
    ("kata kosong", " melakukan"),
    ("kata kosong", " sebenarnya"),
    ("kata kosong", " sama sekali"),
    ("kata kosong", " Untuk mengatasi masalah ini, Anda dapat"),
    ("kata kosong", " dengan menggunakan"),
    ("penutup", " Semoga penjelasan ini membantu, dan jangan ragu untuk bertanya jika ada hal lain yang ingin Anda ketahui!"),
]
# Chisel order: the obvious fluff goes first, the subtle fluff last.
STAGE = {"pembuka": 0, "penutup": 1, "sapaan": 2, "ragu-ragu": 2, "kata kosong": 3}

ABBREV = [("tidak", "tdk"), ("sudah", "udh"), ("dengan", "dgn"), ("karena", "krn"), ("juga", "jg")]


def pieces(text: str) -> list[str]:
    return [ENC.decode([t]) for t in ENC.encode(text)]


def token_spans(text: str) -> list[tuple[int, int, str]]:
    out, pos = [], 0
    for p in pieces(text):
        out.append((pos, pos + len(p), p))
        pos += len(p)
    if pos != len(text):
        sys.exit("token pieces do not reassemble the text")
    return out


def label_fluff(text: str) -> list[dict]:
    toks = token_spans(text)
    starts = {s for s, _, _ in toks} | {len(text)}
    marks: dict[int, str] = {}
    cursor = 0
    for cat, span in FLUFF:
        at = text.find(span, cursor)
        if at < 0:
            sys.exit(f"fluff span not found in order: {span!r}")
        end = at + len(span)
        if at not in starts or end not in starts:
            sys.exit(f"fluff span does not sit on token boundaries: {span!r}")
        for i, (s, e, _) in enumerate(toks):
            if s >= at and e <= end:
                marks[i] = cat
        cursor = end
    return [
        {"t": p, **({"f": marks[i], "s": STAGE[marks[i]]} if i in marks else {})}
        for i, (_, _, p) in enumerate(toks)
    ]


def main() -> None:
    s = next(x for x in SAMPLES if x["id"] == SAMPLE_ID)
    normal = label_fluff(s["normal"])
    fluff_n = sum(1 for t in normal if "f" in t)
    totals = {m: sum(len(ENC.encode(x[m])) for x in SAMPLES) for m in ["normal", *MODES]}
    data = {
        "tokenizer": "o200k_base",
        "prompt": s["prompt"],
        "normal": normal,
        "normalCount": len(normal),
        "fluffCount": fluff_n,
        "afterChisel": len(normal) - fluff_n,
        "singkat": pieces(s["singkat"]),
        "modes": {m: {"text": s[m], "tokens": len(ENC.encode(s[m]))} for m in MODES},
        "abbrev": [
            {"full": f, "fullPieces": pieces(" " + f), "short": a, "shortPieces": pieces(" " + a)}
            for f, a in ABBREV
        ],
        "bench": {
            "samples": len(SAMPLES),
            "normal": totals["normal"],
            **{m: {"tokens": totals[m], "saved": round(100 * (1 - totals[m] / totals["normal"]), 1)} for m in MODES},
        },
        "skillTokens": len(ENC.encode((ROOT / "skills" / "irit" / "SKILL.md").read_text(encoding="utf-8"))),
    }
    OUT.write_text(
        "// Generated by site/tools/build-data.py from benchmarks/samples.json. Do not edit.\n"
        "window.IRIT = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"{OUT.relative_to(ROOT)}: normal {len(normal)} tok, fluff {fluff_n}, after chisel {data['afterChisel']}, "
          f"singkat {len(data['singkat'])}")


if __name__ == "__main__":
    main()
